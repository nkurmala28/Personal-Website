CREATE TABLE IF NOT EXISTS players(id TEXT PRIMARY KEY, token TEXT NOT NULL UNIQUE, name TEXT NOT NULL, score INTEGER NOT NULL DEFAULT -1 CHECK(score BETWEEN -1 AND 5), achieved INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS games(id TEXT PRIMARY KEY, player TEXT NOT NULL, started INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS limits(bucket TEXT PRIMARY KEY, n INTEGER NOT NULL, expires INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS ranking ON players(score DESC, achieved ASC);
